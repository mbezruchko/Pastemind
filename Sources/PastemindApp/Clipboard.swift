import AppKit
import Carbon.HIToolbox
import ImageIO
import PastemindKit
import UniformTypeIdentifiers

/// What a copy put on the pasteboard, as Pastemind keeps it.
enum Capture {
    case text(String, rich: (data: Data, type: String)?)
    case files([URL])
    case image(Data, ext: String)
}

struct CaptureSource: Equatable {
    let appID: String?
    let appName: String?
}

/// Watches the general pasteboard. macOS has no notification for a copy, so it reads `changeCount` four times a second
/// (a counter read: no measurable cost) and the pasteboard itself only when that changes, once the copy has settled.
final class ClipboardWatcher {
    /// On every item Pastemind writes, so its own pastes aren't recorded as copies.
    static let ownType = NSPasteboard.PasteboardType("app.pastemind.own")
    /// Markers apps put on what shouldn't be kept (nspasteboard.org): passwords, one-time and generated content.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]
    /// Bigger copies are skipped: not something to search or paste from a history. A picture can be big as copied:
    /// browsers put a photo there decoded, as a TIFF (48 MB for 12 megapixels), kept as PNG (`Pictures.save`).
    private static let maxTextBytes = 4 << 20
    private static let maxRichBytes = 8 << 20
    nonisolated static let maxImageBytes = 256 << 20
    /// The kinds of picture taken, the first one there: a GIF before its first frame as PNG, the formats apps keep
    /// pictures in before the TIFF they decode them to.
    private static let imageTypes: [(type: NSPasteboard.PasteboardType, ext: String)] = [
        (NSPasteboard.PasteboardType(UTType.gif.identifier), "gif"), (.png, "png"),
        (NSPasteboard.PasteboardType(UTType.jpeg.identifier), "jpg"), (NSPasteboard.PasteboardType(UTType.heic.identifier), "heic"),
        (NSPasteboard.PasteboardType(UTType.webP.identifier), "webp"), (NSPasteboard.PasteboardType("public.avif"), "avif"),
        (.tiff, "tiff"),
    ]

    private let pasteboard = Pasteboards.main
    private var changeCount: Int
    /// A copy seen, read once what's on the pasteboard stays the same from one look to the next: an app clears it,
    /// then writes, and a big picture takes it a moment to encode. Read in between, the copy was empty (or only the
    /// picture's address), and missed: the count doesn't change again. The app in front then is the one it came from.
    private var pending: (types: [String], seen: CFTimeInterval, app: NSRunningApplication?)?
    /// Still empty, or still changing, after this long: read as it is. A Chromium browser clears the pasteboard, then
    /// encodes the picture as PNG: seconds for a big one. Waiting costs a look at the types four times a second.
    private static let patience: CFTimeInterval = 10
    /// `onIncoming` was told of the copy in `pending`: told again when it comes to nothing.
    private var announced = false
    private var timer: Timer?
    var onCapture: (Capture, CaptureSource) -> Void = { _, _ in }
    /// A copy on its way: the pasteboard cleared and still empty (a browser encoding a picture), so the history can
    /// show it at once; nil when it came to nothing. One that's read goes to `onCapture` instead.
    var onIncoming: (CaptureSource?) -> Void = { _ in }

    init() {
        changeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.05
        RunLoop.main.add(timer, forMode: .common)   // also while a menu is open or a window is dragged
        self.timer = timer
    }

    /// After Pastemind writes to the pasteboard itself.
    func skipCurrent() {
        changeCount = pasteboard.changeCount
        drop()
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != changeCount || pending != nil else { return }
        let types = (pasteboard.types ?? []).map(\.rawValue)
        if count != changeCount {
            changeCount = count
            let app = NSWorkspace.shared.frontmostApplication
            pending = (types, CACurrentMediaTime(), app)
            if types.isEmpty { announce(app) }
            return
        }
        guard let seen = pending else { return }
        let waiting = CACurrentMediaTime() - seen.seen < Self.patience
        if types.isEmpty || types != seen.types, waiting {
            pending?.types = types
            return
        }
        let app = seen.app
        if Settings.paused || Self.ignores(app) { return drop() }
        // Nothing to keep yet may be the start of a copy: a page's markup for a picture, before the picture it's
        // still encoding. Looked at again until there's something, or no more waiting.
        guard let capture = read() else {
            if !waiting { drop() }
            return
        }
        pending = nil
        announced = false
        onCapture(capture, CaptureSource(appID: app?.bundleIdentifier, appName: app?.localizedName))
    }

    private static func ignores(_ app: NSRunningApplication?) -> Bool {
        app?.bundleIdentifier.map(Settings.ignoredApps.contains) == true
    }

    private func announce(_ app: NSRunningApplication?) {
        guard !announced, !Settings.paused, !Self.ignores(app) else { return }
        announced = true
        onIncoming(CaptureSource(appID: app?.bundleIdentifier, appName: app?.localizedName))
    }

    /// The copy came to nothing (or was Pastemind's own).
    private func drop() {
        pending = nil
        if announced { onIncoming(nil) }
        announced = false
    }

    private func read() -> Capture? {
        guard let types = pasteboard.types, !types.isEmpty else { return nil }
        let names = Set(types.map(\.rawValue))
        guard !names.contains(Self.ownType.rawValue), names.isDisjoint(with: Self.skippedTypes) else { return nil }

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        let string = pasteboard.string(forType: .string)
        // A picture copied in a browser comes with its address as text (Safari's, Firefox's): the picture is what was
        // copied. Other text beside a picture is the copy (cells in a spreadsheet come with a picture of them too).
        let trimmed = string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if trimmed.isEmpty || ClipClassifier.isLink(trimmed) || trimmed.hasPrefix("data:image/"), let image = image(types) {
            return image
        }
        if let string, string.utf8.count <= Self.maxTextBytes, !trimmed.isEmpty {
            var rich: (Data, String)?
            for type in [NSPasteboard.PasteboardType.rtf, .html] where types.contains(type) {
                if let data = pasteboard.data(forType: type), data.count <= Self.maxRichBytes {
                    rich = (data, type.rawValue)
                    break
                }
            }
            return .text(string, rich: rich)
        }
        return nil
    }

    private func image(_ types: [NSPasteboard.PasteboardType]) -> Capture? {
        for (type, ext) in Self.imageTypes where types.contains(type) {
            if let data = pasteboard.data(forType: type), !data.isEmpty, data.count <= Self.maxImageBytes {
                return .image(data, ext: ext)
            }
        }
        return nil
    }
}

/// Puts a clip back on the pasteboard and, with Accessibility access, presses ⌘V in the app in front.
enum Paster {
    static func write(_ clip: Clip, rich: (data: Data, type: String)?) {
        let pasteboard = Pasteboards.main
        pasteboard.clearContents()
        var items: [NSPasteboardItem] = []
        switch clip.kind {
        case .file:
            for url in clip.fileURLs {
                let item = NSPasteboardItem()
                item.setString(url.absoluteString, forType: .fileURL)
                item.setString(url.path, forType: .string)
                // A picture file with its picture too, as a copied picture comes with its file: an app that takes
                // pictures pastes the picture, Finder and upload fields the file.
                if clip.isPictureFile, let type = UTType(filenameExtension: url.pathExtension),
                   let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize, size <= 64 << 20,
                   let data = try? Data(contentsOf: url) {
                    item.setData(data, forType: NSPasteboard.PasteboardType(type.identifier))
                }
                items.append(item)
            }
        case .image:
            // With its file too: ⌘V in Finder makes "Image 1400×820.png" of it.
            items.append(PictureFiles.item(for: clip) ?? NSPasteboardItem())
        default:
            let item = NSPasteboardItem()
            item.setString(clip.text, forType: .string)
            if let rich { item.setData(rich.data, forType: NSPasteboard.PasteboardType(rich.type)) }
            items.append(item)
        }
        if items.isEmpty { items.append(NSPasteboardItem()) }
        items[0].setData(Data(), forType: ClipboardWatcher.ownType)
        pasteboard.writeObjects(items)
    }

    static var canPaste: Bool { AXIsProcessTrusted() }

    /// Asks macOS for Accessibility access (System Settings opens with Pastemind in the list).
    static func requestAccess() {
        _ = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
    }

    /// ⌘V, as if typed: into whichever app is in front once the panel is gone.
    static func pressCommandV() {
        guard !DebugHooks.enabled else { return log("debug: ⌘V not pressed") }
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(kVK_ANSI_V)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }
}

/// Pictures: saved once by content, measured, and read by OCR (`TextRecognition`) so their text can be searched.
nonisolated enum Pictures {
    struct Saved: Sendable {
        let name: String
        let hash: String
        let width: Int?
        let height: Int?
        let bytes: Int
    }

    /// A TIFF (a picture as an app decoded it: uncompressed) is kept as PNG, the same picture in a fraction of it.
    static func save(_ data: Data, ext: String) throws -> Saved {
        var data = data, ext = ext
        if ext == "tiff", let png = png(from: data) { (data, ext) = (png, "png") }
        let hash = ClipClassifier.hash(data)
        let name = "\(hash).\(ext)"
        let url = AppPaths.images.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) { try data.write(to: url, options: .atomic) }
        let size = pixels(of: CGImageSourceCreateWithData(data as CFData, nil))
        return Saved(name: name, hash: hash, width: size?.width, height: size?.height, bytes: data.count)
    }

    /// The copies to draw: the preview's from the original, the icon's from the preview's. After the clip's in the
    /// list (it shows the moment the picture's saved, its icon a moment later).
    static func makeCopies(_ name: String) {
        _ = decode(name, pixels: previewPixels)
        _ = decode(name, pixels: iconPixels)
    }

    /// A picture file's size in pixels (from its header) and on disk, as a saved picture's: nil when it's gone. A
    /// link's is its file's (its own is the length of the path in it).
    static func measure(_ url: URL) -> (width: Int?, height: Int?, bytes: Int)? {
        let url = url.resolvingSymlinksInPath()
        guard let bytes = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize else { return nil }
        let size = pixels(of: CGImageSourceCreateWithURL(url as CFURL, nil))
        return (size?.width, size?.height, bytes)
    }

    /// A picture file's contents, to keep as a copied picture: nil when it's too big, or can't be read (another app's
    /// data, without access to it).
    static func data(of url: URL) -> Data? {
        guard let bytes = (try? url.resolvingSymlinksInPath().resourceValues(forKeys: [.fileSizeKey]))?.fileSize,
              bytes <= ClipboardWatcher.maxImageBytes else { return nil }
        return try? Data(contentsOf: url)
    }

    private static func pixels(of source: CGImageSource?) -> (width: Int, height: Int)? {
        guard let source, let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return (width, height)
    }

    /// The sizes pictures are drawn at (longest side, in pixels): the list's icon and the preview.
    static let iconPixels = 96
    static let previewPixels = 900

    /// The picture at `pixels` to draw. From its smaller copy when it has one: a 3456×2234 screenshot takes ~40 ms to
    /// decode, its 900-pixel copy ~5 ms. Else from the original, or from a bigger copy, keeping the copy for next time.
    static func decode(_ name: String, pixels: Int) -> CGImage? {
        let copy = copyURL(name, pixels: pixels)
        if let image = thumbnail(of: copy, pixels: pixels) { return image }
        let bigger = pixels < previewPixels ? [copyURL(name, pixels: previewPixels)] : []
        guard let image = (bigger + [AppPaths.images.appendingPathComponent(name)])
            .lazy.compactMap({ thumbnail(of: $0, pixels: pixels) }).first
        else { return nil }
        // A picture no bigger than that decodes as fast as its copy would.
        if max(image.width, image.height) >= pixels { write(image, to: copy) }
        return image
    }

    /// Copies for the pictures saved before there were any: once, in the background (the marker says it's done).
    static func makeMissingCopies() {
        let marker = AppPaths.thumbnails.appendingPathComponent(".made")
        guard !FileManager.default.fileExists(atPath: marker.path) else { return }
        for name in (try? FileManager.default.contentsOfDirectory(atPath: AppPaths.images.path)) ?? [] {
            autoreleasepool {
                _ = decode(name, pixels: previewPixels)
                _ = decode(name, pixels: iconPixels)
            }
        }
        FileManager.default.createFile(atPath: marker.path, contents: nil)
    }

    /// The picture and its copies.
    static func remove(_ name: String) {
        try? FileManager.default.removeItem(at: AppPaths.images.appendingPathComponent(name))
        for pixels in [iconPixels, previewPixels] { try? FileManager.default.removeItem(at: copyURL(name, pixels: pixels)) }
    }

    private static func copyURL(_ name: String, pixels: Int) -> URL {
        AppPaths.thumbnails.appendingPathComponent("\((name as NSString).deletingPathExtension)-\(pixels).png")
    }

    /// The first picture in `data`, as PNG (ImageIO: fine off the main thread).
    private static func png(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let png = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(png, UTType.png.identifier as CFString, 1, nil)
        else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? png as Data : nil
    }

    /// As PNG: it keeps the transparency of window shots (JPEG drops it; HEIC decodes four times slower). Written whole
    /// at once, so a decode that runs alongside never reads half a file.
    private static func write(_ image: CGImage, to url: URL) {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil)
        else { return }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return }
        try? data.write(to: url, options: .atomic)
    }

    /// The text in a picture (screenshots, photos of documents), in reading order. Empty when there's none.
    static func text(in url: URL) -> String {
        TextRecognition.pages(of: url)?.first?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    }

    /// A smaller version, decoded at the size it's drawn. Never bigger than the picture.
    private static func thumbnail(of url: URL, pixels: Int) -> CGImage? {
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: pixels,
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    }
}
